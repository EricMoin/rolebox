import type { ComputerCaptureGuard, ComputerCaptureRequest } from "../../platform/system/types.ts";

export const DARWIN_GEOMETRY_SCRIPT = [
  "ObjC.import('AppKit');",
  "ObjC.import('CoreGraphics');",
  "function computerDisplays() {",
  "  var screens = $.NSScreen.screens;",
  "  if (Number(screens.count) === 0) throw new Error('no displays are available in this desktop session');",
  "  var out = [];",
  "  for (var i = 0; i < Number(screens.count); i++) {",
  "    var screen = screens.objectAtIndex(i);",
  "    var display = Number(screen.deviceDescription.objectForKey('NSScreenNumber').js);",
  "    var bounds = $.CGDisplayBounds(display);",
  "    out.push({id: i + 1, x: bounds.origin.x, y: bounds.origin.y, width: bounds.size.width, height: bounds.size.height, scale: Number(screen.backingScaleFactor), primary: i === 0, name: String(display)});",
  "  }",
  "  return out;",
  "}",
  "function computerCaptureGeometry(target) {",
  "  var displays = computerDisplays();",
  "  var bounds;",
  "  if (target.windowId !== undefined) {",
  "    var list = ObjC.castRefToObject($.CGWindowListCopyWindowInfo($.kCGWindowListOptionOnScreenOnly | $.kCGWindowListExcludeDesktopElements, $.kCGNullWindowID));",
  "    if (!list) throw new Error('the window server did not return a readable window list');",
  "    for (var i = 0; i < Number(list.count); i++) {",
  "      var item = list.objectAtIndex(i);",
  "      if (Number(item.objectForKey('kCGWindowNumber').js) !== target.windowId || Number(item.objectForKey('kCGWindowLayer').js) !== 0) continue;",
  "      var frame = ObjC.deepUnwrap(item.objectForKey('kCGWindowBounds'));",
  "      bounds = {x: frame.X, y: frame.Y, w: frame.Width, h: frame.Height};",
  "      break;",
  "    }",
  "    if (!bounds) throw new Error('the requested window is not visible; refresh computer_windows');",
  "  } else if (target.region !== undefined) {",
  "    bounds = target.region;",
  "  } else {",
  "    var id = target.display === undefined ? 1 : target.display;",
  "    var display = displays.filter(function (entry) { return entry.id === id; })[0];",
  "    if (!display) throw new Error('the requested display is no longer available; refresh computer_displays');",
  "    bounds = {x: display.x, y: display.y, w: display.width, h: display.height};",
  "  }",
  "  if (![bounds.x, bounds.y, bounds.w, bounds.h].every(function (value) { return typeof value === 'number' && isFinite(value); }) || bounds.w <= 0 || bounds.h <= 0) throw new Error('the capture target has invalid screen bounds');",
  "  return {bounds: bounds, displays: displays};",
  "}",
  "function computerSameGeometry(a, b) {",
  "  if (!['x', 'y', 'w', 'h'].every(function (key) { return a.bounds[key] === b.bounds[key]; }) || a.displays.length !== b.displays.length) return false;",
  "  return a.displays.every(function (display, i) {",
  "    return ['id', 'x', 'y', 'width', 'height', 'scale', 'primary', 'name'].every(function (key) { return display[key] === b.displays[i][key]; });",
  "  });",
  "}",
].join("\n");

export function darwinCaptureGuardScript(guard: ComputerCaptureGuard): string {
  return [
    DARWIN_GEOMETRY_SCRIPT,
    `var guard = ${JSON.stringify(guard)};`,
    "var currentGeometry;",
    "try { currentGeometry = computerCaptureGeometry(guard.target); } catch (_) { throw new Error('ROLEBOX_SCREENSHOT_STALE: screenshot geometry changed; take a fresh screenshot'); }",
    "if (!computerSameGeometry(guard.geometry, currentGeometry)) throw new Error('ROLEBOX_SCREENSHOT_STALE: screenshot geometry changed; take a fresh screenshot');",
  ].join("\n");
}

export const DARWIN_COMPOSITE_SCRIPT = [
  "function computerCompositeCapture(bounds, displays, capture) {",
  "  var width = Math.ceil(bounds.w), height = Math.ceil(bounds.h);",
  "  var colorSpace = $.CGColorSpaceCreateDeviceRGB();",
  "  if (!colorSpace) throw new Error('could not create the screenshot color space');",
  "  var canvas;",
  "  try { canvas = $.CGBitmapContextCreate(null, width, height, 8, width * 4, colorSpace, $.kCGImageAlphaPremultipliedLast); }",
  "  finally { $.CGColorSpaceRelease(colorSpace); }",
  "  if (!canvas) throw new Error('could not allocate the screenshot bitmap');",
  "  try {",
  "    $.CGContextClearRect(canvas, $.CGRectMake(0, 0, width, height));",
  "    $.CGContextSetInterpolationQuality(canvas, $.kCGInterpolationHigh);",
  "    var count = 0;",
  "    for (var i = 0; i < displays.length; i++) {",
  "      var display = displays[i];",
  "      var x = Math.max(bounds.x, display.x), y = Math.max(bounds.y, display.y);",
  "      var right = Math.min(bounds.x + bounds.w, display.x + display.width);",
  "      var bottom = Math.min(bounds.y + bounds.h, display.y + display.height);",
  "      if (right <= x || bottom <= y) continue;",
  "      var tile = capture({x: x, y: y, w: right - x, h: bottom - y});",
  "      try {",
  "        if (!(Number($.CGImageGetWidth(tile)) > 0 && Number($.CGImageGetHeight(tile)) > 0)) throw new Error('screencapture returned an empty screenshot image');",
  "        var scaleX = width / bounds.w, scaleY = height / bounds.h;",
  "        var destination = $.CGRectMake((x - bounds.x) * scaleX, height - (bottom - bounds.y) * scaleY, (right - x) * scaleX, (bottom - y) * scaleY);",
  "        $.CGContextDrawImage(canvas, destination, tile);",
  "        count++;",
  "      } finally { $.CGImageRelease(tile); }",
  "    }",
  "    if (count === 0) throw new Error('the capture region does not intersect an available display');",
  "    var image = $.CGBitmapContextCreateImage(canvas);",
  "    if (!image) throw new Error('could not create the composed screenshot image');",
  "    return image;",
  "  } finally { $.CGContextRelease(canvas); }",
  "}",
].join("\n");

export function darwinCaptureScript(request: ComputerCaptureRequest): string {
  const { path, ...target } = request;
  return [
    DARWIN_GEOMETRY_SCRIPT,
    DARWIN_COMPOSITE_SCRIPT,
    "ObjC.import('Foundation');",
    "ObjC.import('ImageIO');",
    "ObjC.bindFunction('umask', ['unsigned int', ['unsigned int']]);",
    "$.umask(63);",
    `var target = ${JSON.stringify(target)};`,
    `var path = ${JSON.stringify(path)};`,
    "var before = computerCaptureGeometry(target);",
    "function computerIsNil(value) { return value === null || value === undefined || (typeof value.isNil === 'function' && value.isNil()); }",
    "function computerReadCapture(args) {",
    "  var files = $.NSFileManager.defaultManager;",
    "  if (!files.createFileAtPathContentsAttributes(path, $.NSData.data, {NSFilePosixPermissions: 384})) throw new Error('could not create the private screenshot file');",
    "  try {",
    "    var task = $.NSTask.alloc.init;",
    "    task.launchPath = '/usr/sbin/screencapture';",
    "    task.arguments = ['-x', '-t', 'png'].concat(args, [path]);",
    "    task.launch;",
    "    task.waitUntilExit;",
    "    if (Number(task.terminationStatus) !== 0) throw new Error('screencapture failed with status ' + Number(task.terminationStatus));",
    "    var data = $.NSData.dataWithContentsOfFile(path);",
    "    if (computerIsNil(data) || Number(data.length) === 0) throw new Error('screencapture did not produce an image');",
    "    var source = $.CGImageSourceCreateWithData(data, null);",
    "    if (computerIsNil(ObjC.castRefToObject(source))) throw new Error('screencapture did not produce a readable image');",
    "    var image;",
    "    try { image = $.CGImageSourceCreateImageAtIndex(source, 0, null); }",
    "    finally { $.CFRelease(ObjC.castRefToObject(source)); }",
    "    if (computerIsNil(ObjC.castRefToObject(image)) || !(Number($.CGImageGetWidth(image)) > 0 && Number($.CGImageGetHeight(image)) > 0)) {",
    "      if (!computerIsNil(ObjC.castRefToObject(image))) $.CGImageRelease(image);",
    "      throw new Error('screencapture returned an empty screenshot image');",
    "    }",
    "    return image;",
    "  } finally { files.removeItemAtPathError(path, null); }",
    "}",
    "var image = target.windowId !== undefined",
    "  ? computerReadCapture(['-o', '-l', String(target.windowId)])",
    "  : computerCompositeCapture(before.bounds, before.displays, function (bounds) {",
    "      return computerReadCapture(['-R', [bounds.x, bounds.y, bounds.w, bounds.h].join(',')]);",
    "    });",
    "try {",
    "  var after = computerCaptureGeometry(target);",
    "  if (!computerSameGeometry(before, after)) throw new Error('screenshot geometry changed; take a fresh screenshot');",
    "  if (!$.NSFileManager.defaultManager.createFileAtPathContentsAttributes(path, $.NSData.data, {NSFilePosixPermissions: 384})) throw new Error('could not create the private screenshot file');",
    "  var destination = $.CGImageDestinationCreateWithURL($.NSURL.fileURLWithPath(path), $('public.png'), 1, null);",
    "  if (computerIsNil(ObjC.castRefToObject(destination))) throw new Error('could not open the screenshot PNG destination');",
    "  try {",
    "    $.CGImageDestinationAddImage(destination, image, null);",
    "    if (!$.CGImageDestinationFinalize(destination)) throw new Error('could not write the screenshot PNG');",
    "  } finally { $.CFRelease(ObjC.castRefToObject(destination)); }",
    "} finally { $.CGImageRelease(image); }",
    "JSON.stringify(before);",
  ].join("\n");
}
