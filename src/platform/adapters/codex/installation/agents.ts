import { createHash, randomUUID } from "node:crypto";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import type { ResolvedRole, ResolvedSubAgent } from "../../../../types.ts";
import { escapeTomlString } from "./plugin-bundle.ts";

export interface CodexAgentMappingOptions {
  /** The effective inherited provider; absent means qualified models cannot be projected. */
  modelProvider?: string;
}

export interface CodexAgentDescriptor {
  roleId: string;
  rootRoleId: string;
  nativeName: string;
  description: string;
  developerInstructions: string;
  parentId?: string;
  model?: string;
  reasoningEffort?: string;
  features?: Record<string, false>;
}

export interface CodexAgentMappings {
  agents: CodexAgentDescriptor[];
  warnings: string[];
}

const REASONING_EFFORTS = new Set(["none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra"]);
const FEATURE_TOOLS: Record<string, readonly string[]> = {
  shell_tool: ["shell_tool", "bash", "shell", "exec_command", "write_stdin"],
  apps: ["apps"],
  plugins: ["plugins"],
  memories: ["memories", "memory_tool"],
  request_permissions_tool: ["request_permissions_tool"],
};
const NATIVE_TOOL_NAMES = new Set(Object.values(FEATURE_TOOLS).flat());
const MANIFEST_NAME = "rolebox-agents.json";
const GENERATED_HEADER = "# Generated by rolebox. Edit role.yaml and sync again.\n";

/** Use readable names for ordinary IDs and a digest for case/path/Unicode collisions. */
export function codexAgentName(roleId: string): string {
  if (roleId.length === 0) throw new Error("A Codex rolebox agent requires a non-empty role ID");
  if (/^[a-z0-9][a-z0-9_-]{0,54}$/.test(roleId)) return `rolebox--${roleId}`;
  const slug = roleId.toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "agent";
  return `rolebox--${slug}-${digest(roleId).slice(0, 12)}`;
}

function mapModel(
  roleId: string,
  model: string | undefined,
  options: CodexAgentMappingOptions,
  warnings: string[],
): string | undefined {
  const value = model?.trim();
  if (!value) return undefined;
  const separator = value.indexOf("/");
  if (separator < 0) return value;
  if (separator > 0 && value.slice(0, separator) === options.modelProvider && value.slice(separator + 1)) {
    return value.slice(separator + 1);
  }
  warnings.push(`Role '${roleId}': the provider-qualified model does not match a known inherited Codex provider; the native agent inherits its parent's model. Use a native model ID or a matching modelProvider.`);
  return undefined;
}

function mapFeatures(
  roleId: string,
  config: ResolvedRole["config"] | ResolvedSubAgent["config"],
  warnings: string[],
): Record<string, false> | undefined {
  const tools = config.tools ?? {};
  const denied = new Set(config.permission?.deny ?? []);
  const features: Record<string, false> = {};
  for (const [feature, aliases] of Object.entries(FEATURE_TOOLS)) {
    if (aliases.some(name => tools[name] === false || [...denied].some(pattern => pattern === name ||
      (pattern.endsWith("*") && name.startsWith(pattern.slice(0, -1))))) ||
      (tools["*"] === false && !aliases.some(name => tools[name] === true))) {
      features[feature] = false;
    }
  }
  if (Object.keys(tools).some(name => tools[name] === false && name !== "*" && !NATIVE_TOOL_NAMES.has(name)) ||
    [...denied].some(name => name !== "*" && !NATIVE_TOOL_NAMES.has(name))) {
    warnings.push(`Role '${roleId}': Codex native agents support feature-level restrictions, not arbitrary per-tool permissions. Individual rolebox MCP tool restrictions require the role-aware runtime.`);
  }
  return Object.keys(features).length > 0 ? features : undefined;
}

export function collectCodexAgentDescriptors(
  roles: readonly ResolvedRole[],
  options: CodexAgentMappingOptions = {},
): CodexAgentMappings {
  const agents: CodexAgentDescriptor[] = [];
  const warnings: string[] = [];
  const ids = new Set<string>();
  const names = new Set<string>();
  function collect(agent: ResolvedRole | ResolvedSubAgent, rootRoleId: string, parentId?: string): void {
    const nativeName = codexAgentName(agent.id);
    if (ids.has(agent.id) || names.has(nativeName)) throw new Error("Duplicate Codex rolebox agent identity");
    ids.add(agent.id);
    names.add(nativeName);
    if (parentId !== undefined && "parentId" in agent && agent.parentId !== parentId) {
      throw new Error(`Role '${agent.id}' has an inconsistent parent identity`);
    }
    const config = agent.config;
    const context = [
      agent.prompt,
      "## Codex rolebox mapping",
      `Your canonical rolebox agent ID is ${JSON.stringify(agent.id)}.`,
      "Codex inherits sandbox, approval policy, model provider and MCP connections from the parent session. Role instructions cannot grant additional authority.",
    ];
    if (agent.subagents.length > 0) {
      context.push(
        "Your private direct children can be used as graph_declare node agents when that tool is available:",
        ...agent.subagents.map(child => `- ${JSON.stringify(child.id)}: ${child.config.description}`),
        "Private child IDs are rolebox execution targets, not globally registered native Codex agent names. Do not discover or address another role's private children.",
      );
    }
    const descriptor: CodexAgentDescriptor = {
      roleId: agent.id,
      rootRoleId,
      nativeName,
      description: config.description.trim() || `Run the ${config.name || agent.id} role.`,
      developerInstructions: context.filter(Boolean).join("\n\n"),
      ...(parentId === undefined ? {} : { parentId }),
    };
    const model = mapModel(agent.id, config.model, options, warnings);
    if (model !== undefined) descriptor.model = model;
    if (config.variant !== undefined) {
      if (REASONING_EFFORTS.has(config.variant)) descriptor.reasoningEffort = config.variant;
      else warnings.push(`Role '${agent.id}': the model variant is not a supported Codex reasoning effort and is omitted.`);
    }
    const features = mapFeatures(agent.id, config, warnings);
    if (features !== undefined) descriptor.features = features;
    if (config.temperature !== undefined || config.top_p !== undefined) {
      warnings.push(`Role '${agent.id}': Codex custom-agent configuration does not expose rolebox sampling parameters; they are omitted.`);
    }
    agents.push(descriptor);
    for (const child of agent.subagents) collect(child, rootRoleId, agent.id);
  }
  for (const role of roles) collect(role, role.id);
  return { agents, warnings };
}

export function renderCodexAgent(descriptor: CodexAgentDescriptor): string {
  const string = (value: string) => `"${escapeTomlString(value)}"`;
  const lines = [
    GENERATED_HEADER.trimEnd(),
    `name = ${string(descriptor.nativeName)}`,
    `description = ${string(descriptor.description)}`,
    `developer_instructions = ${string(descriptor.developerInstructions)}`,
  ];
  if (descriptor.model !== undefined) lines.push(`model = ${string(descriptor.model)}`);
  if (descriptor.reasoningEffort !== undefined) lines.push(`model_reasoning_effort = ${string(descriptor.reasoningEffort)}`);
  if (descriptor.features !== undefined) {
    lines.push("", "[features]");
    for (const feature of Object.keys(descriptor.features).sort()) lines.push(`${feature} = false`);
  }
  return `${lines.join("\n")}\n`;
}

interface ManagedAgentFile {
  name: string;
  sha256: string;
}

function digest(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}

function readManifest(path: string): ManagedAgentFile[] {
  if (!pathExists(path)) return [];
  if (!lstatSync(path).isFile()) throw new Error("The Codex rolebox agent manifest must be a regular file");
  const value: unknown = JSON.parse(readFileSync(path, "utf-8"));
  if (typeof value !== "object" || value === null || !("version" in value) || value.version !== 1 ||
    !("files" in value) || !Array.isArray(value.files)) throw new Error("Invalid Codex rolebox agent manifest");
  const files: ManagedAgentFile[] = [];
  for (const entry of value.files) {
    if (typeof entry !== "object" || entry === null || typeof entry.name !== "string" ||
      !/^rolebox--[a-z0-9_-]+\.toml$/.test(entry.name) || typeof entry.sha256 !== "string" ||
      !/^[a-f0-9]{64}$/.test(entry.sha256) || files.some(file => file.name === entry.name)) {
      throw new Error("Invalid Codex rolebox agent manifest entry");
    }
    files.push({ name: entry.name, sha256: entry.sha256 });
  }
  return files;
}

function sameManagedFile(path: string, previous: ManagedAgentFile | undefined): boolean {
  try {
    return previous !== undefined && lstatSync(path).isFile() &&
      digest(readFileSync(path, "utf-8")) === previous.sha256;
  } catch { return false; }
}

function pathExists(path: string): boolean {
  try { lstatSync(path); return true; } catch (error) {
    if (typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}

function writeAtomic(path: string, content: string): void {
  const temporary = `${path}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temporary, content, { encoding: "utf-8", flag: "wx", mode: 0o600 });
    renameSync(temporary, path);
  } finally {
    try { unlinkSync(temporary); } catch (error) {
      if (!(typeof error === "object" && error !== null && "code" in error && error.code === "ENOENT")) throw error;
    }
  }
}

export interface SyncCodexAgentsOptions extends CodexAgentMappingOptions {
  codexHome: string;
  /** Project roles belong to the project's own Codex layer, never the global layer. */
  projectDir?: string;
}

export interface SyncCodexAgentsResult extends CodexAgentMappings {
  agentDir: string;
  manifestPath: string;
  written: number;
  removed: number;
}

/** Export public roles; private children remain runtime descriptors outside native discovery. */
export function syncCodexAgents(
  roles: readonly ResolvedRole[],
  options: SyncCodexAgentsOptions,
): SyncCodexAgentsResult {
  const mapping = collectCodexAgentDescriptors(roles, options);
  const configDir = options.projectDir === undefined ? options.codexHome : join(options.projectDir, ".codex");
  const agentDir = join(configDir, "agents");
  const manifestPath = join(configDir, MANIFEST_NAME);
  const previous = readManifest(manifestPath);
  const desired = mapping.agents.filter(agent => agent.parentId === undefined);
  const result: SyncCodexAgentsResult = { ...mapping, agentDir, manifestPath, written: 0, removed: 0 };
  if (desired.length === 0 && previous.length === 0) return result;
  if (pathExists(agentDir) && (!lstatSync(agentDir).isDirectory() || lstatSync(agentDir).isSymbolicLink())) {
    result.warnings.push("Codex agents directory is not a regular directory; native agent files were preserved.");
    return result;
  }
  mkdirSync(agentDir, { recursive: true });
  const next = new Map<string, ManagedAgentFile>();
  const desiredNames = new Set(desired.map(agent => `${agent.nativeName}.toml`));
  for (const descriptor of desired) {
    const name = `${descriptor.nativeName}.toml`;
    const path = join(agentDir, name);
    const prior = previous.find(file => file.name === name);
    const content = renderCodexAgent(descriptor);
    if (pathExists(path) && !sameManagedFile(path, prior)) {
      result.warnings.push(`Native Codex agent '${descriptor.nativeName}' has an unmanaged or edited file; it was preserved.`);
      if (prior !== undefined) next.set(name, prior);
      continue;
    }
    if (!pathExists(path) || readFileSync(path, "utf-8") !== content) {
      writeAtomic(path, content);
      result.written++;
    }
    next.set(name, { name, sha256: digest(content) });
  }
  for (const prior of previous) {
    if (desiredNames.has(prior.name)) continue;
    const path = join(agentDir, prior.name);
    if (!pathExists(path)) continue;
    if (sameManagedFile(path, prior)) {
      unlinkSync(path);
      result.removed++;
    } else {
      next.set(prior.name, prior);
      result.warnings.push(`Stale native Codex agent '${prior.name}' has local changes; it was preserved.`);
    }
  }
  const manifest = `${JSON.stringify({ version: 1, files: [...next.values()].sort((a, b) => a.name.localeCompare(b.name)) }, null, 2)}\n`;
  if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf-8") !== manifest) writeAtomic(manifestPath, manifest);
  return result;
}
