import { rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Plugin } from "esbuild";
import * as darwin from "../src/computer/drivers/darwin/native-scripts.ts";
import * as linux from "../src/computer/drivers/linux/native-scripts.ts";
import * as win32 from "../src/computer/drivers/win32/native-scripts.ts";

export const computerScriptPlatforms = ["darwin", "linux", "win32"] as const;
export type ComputerScriptPlatform = typeof computerScriptPlatforms[number];
const nativeScripts = { darwin, linux, win32 };
const sourceModules = new Map(computerScriptPlatforms.map(platform => [
  fileURLToPath(new URL(`../src/computer/drivers/${platform}/native-scripts.ts`, import.meta.url)), platform,
] as const));

export function computerScriptsModule(platform: ComputerScriptPlatform): string {
  return [
    "// Generated by scripts/computer-scripts.ts; edit the native script sources instead.",
    ...Object.entries(nativeScripts[platform]).map(([name, script]) => `export const ${name} = ${JSON.stringify(script)};`),
    "",
  ].join("\n");
}

export function writeComputerScripts(directory: URL): void {
  for (const platform of computerScriptPlatforms) {
    writeFileSync(new URL(`${platform}/native-scripts.js`, directory), computerScriptsModule(platform));
    // tsc's map describes the source loader, which the literal module replaces.
    rmSync(new URL(`${platform}/native-scripts.js.map`, directory), { force: true });
  }
}

export function computerScriptsPlugin(): Plugin {
  return {
    name: "rolebox-computer-scripts",
    setup(build) {
      build.onLoad({ filter: /[/\\]native-scripts\.ts$/ }, ({ path }) => {
        const platform = sourceModules.get(path);
        if (platform !== undefined) return { contents: computerScriptsModule(platform), loader: "js" };
      });
    },
  };
}
